def between(s, a, b):
    i = s.index(a)
    return s[i:s.index(b, i)]


def set_float(body, label, env, place, new_env=None):
    """Change the environment and placement of the float that contains \\label{label}."""
    k = body.index(r"\label{%s}" % label)
    i = body.rindex(r"\begin{%s}" % env, 0, k)
    j = body.index(r"\end{%s}" % env, k)
    opener_end = body.index("\n", i)
    new_env = new_env or env
    inner = body[opener_end:j]
    return body[:i] + r"\begin{%s}[%s]" % (new_env, place) + inner + r"\end{%s}" % new_env + body[j + len(r"\end{%s}" % env):]


def main():
    title = between(SRC, r"\title{", "}\n")[len(r"\title{"):]
    abstract = between(SRC, r"\begin{abstract}", r"\end{abstract}") + r"\end{abstract}"
    body = between(SRC, r"\end{frontmatter}", r"\section*{Data availability}")[len(r"\end{frontmatter}"):]
    data = between(SRC, r"\section*{Data availability}", r"\section*{CRediT")[len(r"\section*{Data availability}"):].strip()

    body = set_float(body, "tab:audit", "table", "!t", "table*")
    body = body.replace(r"p{0.80\linewidth}", r"p{0.86\textwidth}", 1)
    body = set_float(body, "tab:rates", "table", "!t", "table*")
    body = body.replace(r"\resizebox{\linewidth}{!}{%", r"\resizebox{0.85\textwidth}{!}{%", 1)
    body = set_float(body, "tab:classes", "table", "!t")
    body = set_float(body, "fig:refusals", "figure", "!t")
    body = body.replace(r"\includegraphics[width=0.62\linewidth]{fig_refusals.pdf}",
                        r"\includegraphics[width=\columnwidth]{fig_refusals.pdf}", 1)
    body = set_float(body, "fig:ps", "figure", "!t", "figure*")
    assert "!htbp" not in body, "unconverted float"

    first = "Retrieval-augmented generation (RAG) systems answer"
    assert first in body
    body = body.replace(first, r"\IEEEPARstart{R}{etrieval-augmented} generation (RAG) systems answer", 1)

    out = HEAD.replace("%TITLE%", title) + abstract + KEYWORDS + body + TAIL.replace("%DATA%", data)
    (HERE / "main_ieee.tex").write_text(out)
    print("wrote", HERE / "main_ieee.tex")


if __name__ == "__main__":
    main()
